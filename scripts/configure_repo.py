#!/usr/bin/env python3
"""Configure GitHub/Colab links. This script never reads or writes API credentials."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[1]


def validate_repo(repo: str) -> str:
    if not re.fullmatch(r"[A-Za-z0-9](?:[A-Za-z0-9-]{0,38})/[A-Za-z0-9_.-]+", repo):
        raise argparse.ArgumentTypeError("Use a GitHub owner/repository pair, for example your-name/agentic-ai-course.")
    owner, name = repo.split("/")
    if owner.endswith("-") or "--" in owner or name in (".", "..") or repo == "OWNER/REPO":
        raise argparse.ArgumentTypeError("Supply your actual GitHub owner/repository, not the placeholder.")
    return repo


def validate_ref(ref: str) -> str:
    if (not ref or ref.startswith(("-", "/")) or ref.endswith(("/", "."))
            or any(c.isspace() or ord(c) < 32 for c in ref)
            or any(c in ref for c in ("..", "@{", "//", "~", "^", ":", "?", "*", "[", "\\"))
            or any(part.startswith(".") or part.endswith(".lock") for part in ref.split("/"))):
        raise argparse.ArgumentTypeError("Use a valid Git branch or tag name, such as main or course/2026.")
    return ref


def configure(repo: str, ref: str = "main", root: Path = ROOT) -> dict:
    repo, ref = validate_repo(repo), validate_ref(ref)
    config_path = root / "course.json"
    config = json.loads(config_path.read_text(encoding="utf-8"))
    config.update(repo=repo, ref=ref)
    config_path.write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")
    public_config = {"repo": repo, "ref": ref}
    (root / "assets" / "config.js").write_text(
        "// Generated by scripts/configure_repo.py. No credentials belong in this file.\n"
        + "window.COURSE_CONFIG = " + json.dumps(public_config) + ";\n", encoding="utf-8")
    # Only explicitly reserved tokens are changed; no broad replacements in authored prose.
    readme = root / "README.md"
    if readme.exists():
        original = readme.read_text(encoding="utf-8")
        updated = original.replace("__COURSE_REPO__", repo).replace("__COURSE_REF__", quote(ref, safe=""))
        if updated != original:
            readme.write_text(updated, encoding="utf-8")
    return public_config


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("repo", type=validate_repo, help="GitHub owner/repository; the repository must already exist when students use Colab links")
    parser.add_argument("--ref", type=validate_ref, default="main", help="Published branch or tag (default: main)")
    args = parser.parse_args()
    config = configure(args.repo, args.ref)
    print(f"Configured {config['repo']} at {config['ref']}.")
    print("Next: commit/push the course and enable GitHub Pages. This command does not publish anything.")


if __name__ == "__main__":
    main()
