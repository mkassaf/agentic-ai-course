#!/usr/bin/env python3
"""Check portable site links and clean, self-contained teaching notebooks."""
from html.parser import HTMLParser
from pathlib import Path
import json
import re
import urllib.parse

import nbformat
from build_notebooks import review_note

ROOT = Path(__file__).resolve().parents[1]


class LinkCollector(HTMLParser):
    def __init__(self):
        super().__init__()
        self.links = []
        self.ids = []

    def handle_starttag(self, tag, attrs):
        data = dict(attrs)
        if "id" in data:
            self.ids.append(data["id"])
        for key in ("href", "src"):
            if key in data:
                self.links.append(data[key])


def main():
    issues = []
    page = LinkCollector()
    page.feed((ROOT / "index.html").read_text())
    config = json.loads((ROOT / "course.json").read_text())
    lesson_data = re.search(r"const labs = (\[.*?\]);", (ROOT / "assets" / "course.js").read_text(), re.S)
    if lesson_data is None or [lab["file"] for lab in json.loads(lesson_data[1])] != config.get("labs"):
        issues.append("Website lessons do not match the configured notebook sequence")
    site_labs = {lab["file"]: lab for lab in json.loads(lesson_data[1])} if lesson_data else {}
    if site_labs:
        for lab in site_labs.values():
            picture = lab.get("picture")
            if picture and not (ROOT / picture.get("src", "")).is_file():
                issues.append(f"{lab['file']}: website illustration is missing")
            tool = lab.get("tool")
            if tool and not (ROOT / tool.get("src", "")).is_file():
                issues.append(f"{lab['file']}: interactive tool is missing")
        expected_tracks = {"lecture-1": 3, "lecture-2": 3, "lecture-3": 3, "self-study": 9}
        for track, count in expected_tracks.items():
            if sum(lab.get("track") == track for lab in site_labs.values()) != count:
                issues.append(f"Website track {track} does not contain {count} labs")
    # Lesson disclosures are generated by assets/course.js from this sequence.
    dynamic_ids = {f"lab-{i:02d}" for i, _ in enumerate(config.get("labs", []))}
    # So are the section headings, one per track.
    track_data = re.search(r"const tracks = (\[.*?\]);", (ROOT / "assets" / "course.js").read_text(), re.S)
    dynamic_ids |= {f"track-{track['id']}" for track in json.loads(track_data[1])} if track_data else set()
    if len(page.ids) != len(set(page.ids)):
        issues.append("Duplicate HTML IDs")
    for link in page.links:
        parsed = urllib.parse.urlsplit(link)
        if parsed.scheme or parsed.netloc:
            continue
        if parsed.path and not (ROOT / urllib.parse.unquote(parsed.path)).exists():
            issues.append(f"Missing local site target: {link}")
        if not parsed.path and parsed.fragment and parsed.fragment not in set(page.ids) | dynamic_ids:
            issues.append(f"Missing site anchor: {link}")
    if not config.get("ref"):
        issues.append("Course ref is missing")
    paths = sorted((ROOT / "notebooks").glob("*.ipynb"))
    expected = set(config.get("labs", []))
    if {path.stem for path in paths} != expected:
        issues.append("Notebook filenames do not match the configured lab sequence")
    if len(paths) != len(config.get("labs", [])):
        issues.append(f"Expected {len(config.get('labs', []))} notebooks; found {len(paths)}")
    for path in paths:
        if not (ROOT / "lessons" / (path.stem + ".json")).exists():
            issues.append(f"{path.name}: editable lesson source is missing")
        notebook = nbformat.read(path, as_version=4)
        nbformat.validate(notebook)
        text = "\n".join(c.source for c in notebook.cells)
        lesson = json.loads((ROOT / "lessons" / (path.stem + ".json")).read_text())
        site_lab = site_labs.get(path.stem, {})
        if site_lab.get("title") != lesson.get("title"):
            issues.append(f"{path.name}: website title differs from the lesson source")
        if site_lab.get("id") != path.stem[:2]:
            issues.append(f"{path.name}: website lab number differs from the notebook")
        review = lesson.get("review", {})
        site_review = site_labs.get(path.stem, {}).get("review", {})
        if {key: site_review.get(key) for key in ("sources", "concepts", "questions")} != review:
            issues.append(f"{path.name}: website lecture references differ from the lesson source")
        if len(review.get("questions", [])) < 2 or not review.get("concepts") or not review.get("sources"):
            issues.append(f"{path.name}: needs slide sources, concepts, and two recall questions")
        elif review_note(lesson) not in text:
            issues.append(f"{path.name}: lecture revision differs from its lesson source; rebuild")
        if re.search(r"team_size\s*>=\s*8|search_hotels|book_room", text):
            issues.append(f"{path.name}: obsolete unrelated example or team-size threshold")
        if re.search(r"MODE\s*=\s*[\"\']practice|(?:example|practice)=", text):
            issues.append(f"{path.name}: remove scripted model-response mode and arguments")
        examples = [c for c in notebook.cells if c.cell_type == "code"
                    and not {"setup", "optional"}.intersection(c.metadata.get("tags", []))]
        optional = [c for c in notebook.cells if c.cell_type == "code"
                    and "optional" in c.metadata.get("tags", [])]
        if any(len(c.source.splitlines()) > 25 for c in optional):
            issues.append(f"{path.name}: an optional example exceeds 25 lines")
        # Each core step is one short cell, so a beginner reads one idea at a time.
        if site_labs.get(path.stem, {}).get("steps") != len(examples):
            issues.append(f"{path.name}: website core-step count differs from the notebook")
        if site_lab.get("optional_examples", 0) != len(optional):
            issues.append(f"{path.name}: website optional-example count differs from the notebook")
        numbered_steps = [int(number) for cell in notebook.cells if cell.cell_type == "markdown"
                          for number in re.findall(r"^## Step (\d+)(?![\w])", cell.source, re.M)]
        if numbered_steps != list(range(1, len(examples) + 1)):
            issues.append(f"{path.name}: numbered headings do not match the core steps")
        if not 2 <= len(examples) <= 5:
            issues.append(f"{path.name}: use two to five step code cells")
        if any(len(c.source.splitlines()) > 25 for c in examples):
            issues.append(f"{path.name}: a step cell exceeds 25 lines; split it into two steps")
        if sum(len(c.source.splitlines()) for c in examples) > 100:
            issues.append(f"{path.name}: example code exceeds the 100-line lab limit")
        for cell in notebook.cells:
            if cell.cell_type == "code":
                if cell.get("outputs") or cell.get("execution_count") is not None:
                    issues.append(f"{path.name}: clear saved execution outputs")
                if re.search(r"(?:sk-[A-Za-z0-9]{16,}|Bearer\s+[A-Za-z0-9]{20,})", cell.source):
                    issues.append(f"{path.name}: potential literal credential")
    if issues:
        raise SystemExit("\n".join(issues))
    print(f"PASS course structure: {len(paths)} clean notebooks; local site links resolve")
    if config.get("repo") in (None, "OWNER/REPO", ""):
        print("Repository links unconfigured: run scripts/configure_repo.py before publishing.")


if __name__ == "__main__":
    main()
