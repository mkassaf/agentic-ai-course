#!/usr/bin/env python3
"""Check portable site links and clean, self-contained teaching notebooks."""
from html.parser import HTMLParser
from pathlib import Path
import json
import re
import urllib.parse

import nbformat

ROOT = Path(__file__).resolve().parents[1]


class LinkCollector(HTMLParser):
    def __init__(self):
        super().__init__()
        self.links = []
        self.ids = []

    def handle_starttag(self, tag, attrs):
        data = dict(attrs)
        if "id" in data:
            self.ids.append(data["id"])
        for key in ("href", "src"):
            if key in data:
                self.links.append(data[key])


def main():
    issues = []
    page = LinkCollector()
    page.feed((ROOT / "index.html").read_text())
    config = json.loads((ROOT / "course.json").read_text())
    lesson_data = re.search(r"const labs = (\[.*?\]);", (ROOT / "assets" / "course.js").read_text(), re.S)
    if lesson_data is None or [lab["file"] for lab in json.loads(lesson_data[1])] != config.get("labs"):
        issues.append("Website lessons do not match the configured notebook sequence")
    # Lesson disclosures are generated by assets/course.js from this sequence.
    dynamic_ids = {f"lab-{i:02d}" for i, _ in enumerate(config.get("labs", []))}
    if len(page.ids) != len(set(page.ids)):
        issues.append("Duplicate HTML IDs")
    for link in page.links:
        parsed = urllib.parse.urlsplit(link)
        if parsed.scheme or parsed.netloc:
            continue
        if parsed.path and not (ROOT / urllib.parse.unquote(parsed.path)).exists():
            issues.append(f"Missing local site target: {link}")
        if not parsed.path and parsed.fragment and parsed.fragment not in set(page.ids) | dynamic_ids:
            issues.append(f"Missing site anchor: {link}")
    if not config.get("ref"):
        issues.append("Course ref is missing")
    paths = sorted((ROOT / "notebooks").glob("*.ipynb"))
    expected = set(config.get("labs", []))
    if {path.stem for path in paths} != expected:
        issues.append("Notebook filenames do not match the configured lab sequence")
    if len(paths) != 8:
        issues.append(f"Expected 8 notebooks; found {len(paths)}")
    for path in paths:
        if not (ROOT / "lessons" / (path.stem + ".json")).exists():
            issues.append(f"{path.name}: editable lesson source is missing")
        notebook = nbformat.read(path, as_version=4)
        nbformat.validate(notebook)
        text = "\n".join(c.source for c in notebook.cells)
        if "make_ask" in text and ("practice" not in text or "live" not in text):
            issues.append(f"{path.name}: needs practice and live explanations")
        examples = [c for c in notebook.cells if c.cell_type == "code" and "setup" not in c.metadata.get("tags", [])]
        if not 1 <= len(examples) <= 2:
            issues.append(f"{path.name}: keep one or two example code cells")
        if sum(len(c.source.splitlines()) for c in examples) > 20:
            issues.append(f"{path.name}: example exceeds the 20-line beginner limit")
        if sum(len(c.source.splitlines()) for c in notebook.cells if c.cell_type == "code") > 25:
            issues.append(f"{path.name}: notebook exceeds 25 Python lines including setup")
        for cell in notebook.cells:
            if cell.cell_type == "code":
                if cell.get("outputs") or cell.get("execution_count") is not None:
                    issues.append(f"{path.name}: clear saved execution outputs")
                if re.search(r"(?:sk-[A-Za-z0-9]{16,}|Bearer\s+[A-Za-z0-9]{20,})", cell.source):
                    issues.append(f"{path.name}: potential literal credential")
    if issues:
        raise SystemExit("\n".join(issues))
    print(f"PASS course structure: {len(paths)} clean notebooks; local site links resolve")
    if config.get("repo") in (None, "OWNER/REPO", ""):
        print("Repository links unconfigured: run scripts/configure_repo.py before publishing.")


if __name__ == "__main__":
    main()
